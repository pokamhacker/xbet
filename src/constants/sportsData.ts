export function getLeaguesByCategory(category: LeagueData['category']): LeagueData[] {
  return EXTENDED_LEAGUES_DATA.filter((l) => l.category === category);
}

export function getLeagueById(id: string): LeagueData | undefined {
  return EXTENDED_LEAGUES_DATA.find((l) => l.id === id);
}

export function getClubById(leagueId: string, clubId: string): Club | undefined {
  const league = getLeagueById(leagueId);
  return league?.clubs.find((c) => c.id === clubId);
}

export function getMajorLeagues(): LeagueData[] {
  return EXTENDED_LEAGUES_DATA.filter((l) => l.isMajor);
}

export function getAllClubs(): Club[] {
  const clubs: Club[] = [];
  EXTENDED_LEAGUES_DATA.forEach((league) => {
    clubs.push(...league.clubs);
  });
  return clubs;
}

export function searchClubs(query: string): Club[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return getAllClubs().filter(
    (club) =>
      club.name.toLowerCase().includes(q) ||
      club.shortCode.toLowerCase().includes(q)
  );
}
